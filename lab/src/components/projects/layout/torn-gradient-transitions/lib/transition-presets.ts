/** Rolls the shape/material dials while keeping the current palette and timing. */
export function randomizeSettings(
  base: TornTransitionSettings,
): TornTransitionSettings {
  const next = { ...base };
  for (const [key, range] of Object.entries(RANDOM_RANGES)) {
    if (!range) continue;
    const [min, max] = range;
    const value = min + Math.random() * (max - min);
    (next as Record<string, unknown>)[key] = Number(value.toFixed(3));
  }
  return next;
}
