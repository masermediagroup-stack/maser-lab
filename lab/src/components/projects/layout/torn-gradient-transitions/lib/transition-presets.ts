export function findPreset(id: string): TornTransitionPreset | undefined {
  return TRANSITION_PRESETS.find((p) => p.id === id);
}

export function presetSettings(id: string): TornTransitionSettings {
  return findPreset(id)?.settings ?? DEFAULT_SETTINGS;
}

